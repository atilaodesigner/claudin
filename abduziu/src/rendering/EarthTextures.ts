export interface EarthTextures {
  day: Texture;
  /** r: city lights, g: land mask. */
  lights: Texture;
  clouds: Texture;
  moon: Texture;
}

function makeCanvas(w: number, h: number): [HTMLCanvasElement, CanvasRenderingContext2D] {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const ctx = c.getContext('2d');
  if (!ctx) throw new Error('2D canvas unavailable');
  return [c, ctx];
}

/** Traces every continent with a little seeded coastline wobble so edges don't look polygonal. */
function traceLand(ctx: CanvasRenderingContext2D, W: number, H: number, rng: Rng): void {
  const X = (lon: number) => ((lon + 180) / 360) * W;
  const Y = (lat: number) => ((90 - lat) / 180) * H;
  ctx.beginPath();
  for (const poly of ALL) {
    const pts: Array<[number, number]> = [];
    for (let i = 0; i < poly.length; i++) {
      const a = poly[i] as readonly [number, number];
      const b = poly[(i + 1) % poly.length] as readonly [number, number];
      const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
      const n = Math.max(1, Math.round(len / 0.9));
      for (let k = 0; k < n; k++) {
        const t = k / n;
        const nx = -(b[1] - a[1]) / (len || 1);
        const ny = (b[0] - a[0]) / (len || 1);
        const j = k === 0 ? 0 : (rng.next() - 0.5) * Math.min(0.9, len * 0.15);
        pts.push([X(a[0] + (b[0] - a[0]) * t + nx * j), Y(a[1] + (b[1] - a[1]) * t + ny * j)]);
      }
    }
    const first = pts[0] as [number, number];
    const last = pts[pts.length - 1] as [number, number];
    ctx.moveTo((first[0] + last[0]) / 2, (first[1] + last[1]) / 2);
    for (let i = 0; i < pts.length; i++) {
      const p = pts[i] as [number, number];
      const q = pts[(i + 1) % pts.length] as [number, number];
      ctx.quadraticCurveTo(p[0], p[1], (p[0] + q[0]) / 2, (p[1] + q[1]) / 2);
    }
    ctx.closePath();
  }
  // Antarctica: a wobbly band around the south pole
  const yA = (lat: number) => Y(lat);
  ctx.moveTo(0, H);
  for (let lon = -180; lon <= 180; lon += 4) {
    const lat = -71 + Math.sin(lon * 0.05) * 3 + Math.sin(lon * 0.13 + 1) * 1.6 + (lon > -75 && lon < -55 ? 7 * Math.cos(((lon + 65) / 10) * Math.PI * 0.5) : 0);
    ctx.lineTo(X(lon), yA(lat));
  }
  ctx.lineTo(W, H);
  ctx.closePath();
}

function blobs(ctx: CanvasRenderingContext2D, W: number, H: number, list: ReadonlyArray<[number, number, number, number]>, color: string, rng: Rng, n: number): void {
  const X = (lon: number) => ((lon + 180) / 360) * W;
  const Y = (lat: number) => ((90 - lat) / 180) * H;
  for (const [lon, lat, rl, rt] of list) {
    for (let i = 0; i < n; i++) {
      const x = X(lon + (rng.next() - 0.5) * rl * 1.6);
      const y = Y(lat + (rng.next() - 0.5) * rt * 1.6);
      const r = ((rl / 360) * W) * (0.25 + rng.next() * 0.4);
      const g = ctx.createRadialGradient(x, y, 0, x, y, r);
      g.addColorStop(0, color);
      g.addColorStop(1, 'rgba(0,0,0,0)');
      ctx.fillStyle = g;
      ctx.fillRect(x - r, y - r * 0.6, r * 2, r * 1.2);
    }
  }
}

export function createEarthTextures(hi: boolean): EarthTextures {
  const rng = new Rng(20260928);
  const W = hi ? 4096 : 2048;
  const H = W / 2;
  const s = W / 4096;

  // ── land mask
  const [maskC, mask] = makeCanvas(W, H);
  mask.fillStyle = '#fff';
  traceLand(mask, W, H, new Rng(77));
  mask.fill('nonzero');

  // ── land colours: latitude bands, then biomes
  const [landC, land] = makeCanvas(W, H);
  const band = land.createLinearGradient(0, 0, 0, H);
  const stops: Array<[number, string]> = [
    [0, '#f4f7fa'], [0.06, '#e9eef2'], [0.1, '#9aa39a'], [0.14, '#5d7550'], [0.2, '#3f6b37'], [0.27, '#5c8a3e'], [0.31, '#a39a63'],
    [0.36, '#c9a86a'], [0.4, '#b99a5c'], [0.44, '#6f9a43'], [0.5, '#2f7a2e'], [0.56, '#3d8733'], [0.6, '#7e9a4a'], [0.64, '#b59e66'],
    [0.7, '#8a9b52'], [0.76, '#5d7f45'], [0.82, '#7c8d7a'], [0.86, '#e3e9ee'], [1, '#f7fafc'],
  ];
  for (const [o, c] of stops) band.addColorStop(o, c);
  land.fillStyle = band;
  land.fillRect(0, 0, W, H);
  blobs(land, W, H, DESERTS, 'rgba(214,178,112,0.9)', rng, 10);
  blobs(land, W, H, JUNGLES, 'rgba(24,96,34,0.9)', rng, 10);
  // mottling: darker/lighter speckles make the land read as terrain from orbit
  for (let i = 0; i < 9000 * s * s + 2500; i++) {
    const x = rng.next() * W;
    const y = rng.next() * H;
    const r = (2 + rng.next() * 9) * s;
    land.fillStyle = rng.next() < 0.5 ? `rgba(30,55,20,${0.03 + rng.next() * 0.06})` : `rgba(230,210,160,${0.03 + rng.next() * 0.07})`;
    land.beginPath();
    land.arc(x, y, r, 0, Math.PI * 2);
    land.fill();
  }
  // mountain ranges as pale ridges (Andes, Himalaya, Rockies, Alps)
  land.strokeStyle = 'rgba(225,215,195,0.22)';
  land.filter = `blur(${Math.max(1, Math.round(3 * s))}px)`;
  land.lineCap = 'round';
  const ridge = (pts: ReadonlyArray<[number, number]>, w: number) => {
    land.lineWidth = w * s;
    land.beginPath();
    pts.forEach(([lon, lat], i) => (i ? land.lineTo(((lon + 180) / 360) * W, ((90 - lat) / 180) * H) : land.moveTo(((lon + 180) / 360) * W, ((90 - lat) / 180) * H)));
    land.stroke();
  };
  ridge([[-75, 8], [-77, 0], [-76, -10], [-70, -18], [-69, -28], [-70.5, -36], [-72, -46], [-73, -52]], 7);
  ridge([[73, 36], [78, 34], [84, 29.5], [90, 28], [96, 29]], 12);
  ridge([[-120, 58], [-116, 50], [-110, 44], [-107, 38], [-106, 32]], 8);
  ridge([[6, 45.5], [10, 46.5], [14, 47]], 6);
  land.filter = 'none';
  land.globalCompositeOperation = 'destination-in';
  land.drawImage(maskC, 0, 0);
  land.globalCompositeOperation = 'source-over';

  // ── day map: ocean, shallow shelves, land
  const [dayC, day] = makeCanvas(W, H);
  const ocean = day.createLinearGradient(0, 0, 0, H);
  ocean.addColorStop(0, '#0d2d4f');
  ocean.addColorStop(0.3, '#0b3a66');
  ocean.addColorStop(0.5, '#0a4176');
  ocean.addColorStop(0.7, '#0b3a66');
  ocean.addColorStop(1, '#0d2d4f');
  day.fillStyle = ocean;
  day.fillRect(0, 0, W, H);
  for (let i = 0; i < 1800; i++) {
    const x = rng.next() * W;
    const y = rng.next() * H;
    const r = (20 + rng.next() * 80) * s;
    day.fillStyle = `rgba(${rng.next() < 0.5 ? '4,20,50' : '20,80,130'},${0.05 + rng.next() * 0.06})`;
    day.beginPath();
    day.arc(x, y, r, 0, Math.PI * 2);
    day.fill();
  }
  // continental shelf: a blurred, teal copy of the coastline under the land
  const [shelfC, shelf] = makeCanvas(W, H);
  shelf.filter = `blur(${Math.max(2, Math.round(10 * s))}px)`;
  shelf.drawImage(maskC, 0, 0);
  shelf.filter = 'none';
  shelf.globalCompositeOperation = 'source-in';
  shelf.fillStyle = '#1f8aa0';
  shelf.fillRect(0, 0, W, H);
  day.globalAlpha = 0.6;
  day.drawImage(shelfC, 0, 0);
  day.globalAlpha = 1;
  day.drawImage(landC, 0, 0);

  // ── night lights (r) + land mask (g), half resolution
  const LW = W / 2;
  const LH = H / 2;
  const [lightC, light] = makeCanvas(LW, LH);
  light.fillStyle = '#000';
  light.fillRect(0, 0, LW, LH);
  const lx = (lon: number) => ((lon + 180) / 360) * LW;
  const ly = (lat: number) => ((90 - lat) / 180) * LH;
  light.fillStyle = 'rgb(255,0,0)';
  for (let i = 0; i < 22000 * s + 6000; i++) {
    const lat = -50 + rng.next() * 110;
    const lon = -180 + rng.next() * 360;
    const k = Math.abs(lat) > 60 ? 0.2 : 1;
    if (rng.next() > k) continue;
    light.globalAlpha = 0.15 + rng.next() * 0.5;
    light.fillRect(lx(lon), ly(lat), 1 + rng.next() * 1.4, 1 + rng.next() * 1.4);
  }
  for (const [lon, lat, size] of METROS) {
    for (let i = 0; i < 70 * size; i++) {
      const a = rng.next() * Math.PI * 2;
      const d = Math.pow(rng.next(), 1.8) * size * 1.4;
      light.globalAlpha = 0.4 + rng.next() * 0.6;
      light.fillRect(lx(lon + Math.cos(a) * d), ly(lat + Math.sin(a) * d * 0.8), 1.4, 1.4);
    }
  }
  light.globalAlpha = 1;
  light.globalCompositeOperation = 'destination-in';
  light.drawImage(maskC, 0, 0, LW, LH);
  light.globalCompositeOperation = 'lighter';
  light.filter = 'none';
  // land mask into the green channel
  const [gC, g] = makeCanvas(LW, LH);
  g.drawImage(maskC, 0, 0, LW, LH);
  g.globalCompositeOperation = 'multiply';
  g.fillStyle = 'rgb(0,255,0)';
  g.fillRect(0, 0, LW, LH);
  light.drawImage(gC, 0, 0);
  light.globalCompositeOperation = 'source-over';

  // ── clouds: bands of soft puffs (tropics, storm tracks) plus a few cyclone swirls
  const CW = Math.min(2048, W);
  const CH = CW / 2;
  const [cloudC, cl] = makeCanvas(CW, CH);
  cl.fillStyle = '#000';
  cl.fillRect(0, 0, CW, CH);
  const cs = CW / 2048;
  const puff = (x: number, y: number, r: number, a: number) => {
    const gr = cl.createRadialGradient(x, y, 0, x, y, r);
    gr.addColorStop(0, `rgba(255,255,255,${a})`);
    gr.addColorStop(1, 'rgba(255,255,255,0)');
    cl.fillStyle = gr;
    cl.fillRect(x - r, y - r, r * 2, r * 2);
  };
  const lats: Array<[number, number, number]> = [
    [5, 7, 0.9], [-8, 6, 0.5], [45, 12, 1], [-48, 10, 1.1], [60, 8, 0.8], [-60, 6, 0.9], [25, 10, 0.25], [-25, 10, 0.35],
  ];
  for (const [lat, spread, dens] of lats) {
    const n = Math.round(900 * dens);
    for (let i = 0; i < n; i++) {
      const x = rng.next() * CW;
      const y = ((90 - (lat + (rng.next() - 0.5) * 2 * spread)) / 180) * CH;
      puff(x, y, (6 + rng.next() * 22) * cs, 0.12 + rng.next() * 0.3);
    }
  }
  for (let k = 0; k < 16; k++) {
    const cx = rng.next() * CW;
    const clat = (rng.next() < 0.5 ? 1 : -1) * (15 + rng.next() * 45);
    const cy = ((90 - clat) / 180) * CH;
    const turns = 2.2;
    for (let i = 0; i < 120; i++) {
      const t = i / 120;
      const a = t * turns * Math.PI * 2 * (clat > 0 ? 1 : -1);
      const rr = t * (40 + rng.next() * 8) * cs;
      puff(cx + Math.cos(a) * rr * 1.5, cy + Math.sin(a) * rr, (4 + (1 - t) * 10) * cs, 0.25);
    }
  }
  // small random fair-weather cumulus everywhere
  for (let i = 0; i < 2500; i++) puff(rng.next() * CW, (0.1 + rng.next() * 0.8) * CH, (2 + rng.next() * 6) * cs, 0.1 + rng.next() * 0.2);

  // ── moon
  const [moonC, mo] = makeCanvas(512, 256);
  mo.fillStyle = '#9a9a96';
  mo.fillRect(0, 0, 512, 256);
  for (let i = 0; i < 90; i++) {
    const x = rng.next() * 512;
    const y = 30 + rng.next() * 196;
    const r = 4 + rng.next() * (i < 8 ? 50 : 14);
    mo.fillStyle = i < 8 ? 'rgba(70,70,72,0.5)' : rng.next() < 0.5 ? 'rgba(60,60,60,0.35)' : 'rgba(200,200,195,0.3)';
    mo.beginPath();
    mo.arc(x, y, r, 0, Math.PI * 2);
    mo.fill();
  }

  const tex = (c: HTMLCanvasElement, srgb: boolean): Texture => {
    const t = new CanvasTexture(c);
    if (srgb) t.colorSpace = SRGBColorSpace;
    t.wrapS = RepeatWrapping;
    t.minFilter = LinearMipmapLinearFilter;
    t.anisotropy = 8;
    t.generateMipmaps = true;
    return t;
  };
  void dayC;
  return { day: tex(dayC, true), lights: tex(lightC, false), clouds: tex(cloudC, false), moon: tex(moonC, true) };
}
